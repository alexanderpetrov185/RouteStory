"""Generates the whoosh cue that VideoExportUseCase.encodeMixedAudio() mixes over the BGM.

Run from the repository root:  python tools/make_sfx.py

Produces (plain 16-bit PCM WAV, mono 22050 Hz, canonical 44-byte header):
  app/src/main/res/raw/whoosh.wav   ~0.8 s car pass-by ("ньюу"): band-passed noise whose
                                    centre sweeps 2.6 kHz -> 0.4 kHz plus a low rumble
                                    sweep 200 -> 65 Hz. NOT white noise: the narrow moving
                                    band keeps the zero-crossing rate far below the
                                    noise-like threshold of the export's audio check.

The photo cue (res/raw/shutter.wav) has its own generator: tools/make_shutter.py.

Manual tool, not part of the Gradle build (no third-party audio, no licensing obligations).
"""

import math
import random
import struct
import wave

SR = 22050


def clamp(v: int) -> int:
    return max(-32767, min(32767, v))


def smoothstep(x: float) -> float:
    x = max(0.0, min(1.0, x))
    return x * x * (3.0 - 2.0 * x)


# ---------------------------------------------------------------- whoosh.wav
def make_whoosh(seconds: float = 0.8) -> list:
    n = int(SR * seconds)
    rnd = random.Random(99)  # deterministic across runs / platforms
    buf = [0.0] * n

    def amp_at(t: float) -> float:
        # Quick rise, long tail: a car passing the camera.
        if t < 0.18:
            return smoothstep(t / 0.18)
        return smoothstep((1.0 - t) / 0.82)

    # Band-passed noise whose centre sweeps down 2.6 kHz -> 0.4 kHz (Doppler pass-by).
    hp = 0.0
    lp = 0.0
    for i in range(n):
        t = i / n
        centre = 2600.0 + (400.0 - 2600.0) * (t ** 0.7)
        hp_a = 1.0 - math.exp(-2.0 * math.pi * (centre * 0.45) / SR)
        lp_a = 1.0 - math.exp(-2.0 * math.pi * (centre * 2.2) / SR)
        hp += hp_a * (rnd.uniform(-1.0, 1.0) - hp)
        lp += lp_a * (hp - lp)
        buf[i] = lp * amp_at(t)

    # Low rumble sweeping 200 -> 65 Hz: the body of the vehicle. Phase is integrated
    # (not re-derived per sample), so the sweep stays a tone, never a click storm.
    phase = 0.0
    for i in range(n):
        t = i / n
        f = 200.0 + (65.0 - 200.0) * t
        phase += 2.0 * math.pi * f / SR
        buf[i] += 0.22 * math.sin(phase) * amp_at(t)

    peak = max(abs(v) for v in buf) or 1.0
    scale = 0.35 / peak  # sits ~9 dB under the BGM peak, gain 0.6 in the mixer
    return [clamp(int(round(v * scale * 32767))) for v in buf]


# ---------------------------------------------------------------- shutter.wav
def make_shutter() -> list:
    length = int(0.15 * SR)
    random.seed(7)
    buf = [0.0] * length

    # 1) 4 ms white-noise "click" burst at t=0 (shutter blade hitting).
    click_len = int(0.004 * SR)
    for i in range(click_len):
        amp = 0.9 * (1.0 - i / click_len)
        buf[i] += random.uniform(-1.0, 1.0) * amp

    # 2) 3 kHz tick with ~20 ms decay (the "snap" of the mirror/blade).
    tick_start = int(0.006 * SR)
    tick_len = int(0.020 * SR)
    w = 2.0 * math.pi * 3000.0 / SR
    for i in range(tick_len):
        buf[tick_start + i] += 0.55 * math.exp(-i / (0.010 * SR)) * math.sin(w * i)

    # 3) 1.2 kHz "thunk" with ~60 ms decay (mechanical body settling).
    thunk_start = int(0.014 * SR)
    thunk_len = int(0.060 * SR)
    w2 = 2.0 * math.pi * 1200.0 / SR
    for i in range(thunk_len):
        idx = thunk_start + i
        if idx >= length:
            break
        buf[idx] += 0.5 * math.exp(-i / (0.030 * SR)) * math.sin(w2 * i)

    peak = max(abs(v) for v in buf) or 1.0
    scale = 0.45 / peak
    return [clamp(int(round(v * scale * 32767))) for v in buf]


def write_wav(path: str, samples: list) -> None:
    with wave.open(path, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(b"".join(struct.pack("<h", s) for s in samples))


whoosh = make_whoosh()

write_wav("app/src/main/res/raw/whoosh.wav", whoosh)

print("wrote res/raw/whoosh.wav   frames=%d (%.2f s) peak=%d/32767" % (
    len(whoosh), len(whoosh) / SR, max(abs(s) for s in whoosh)))
print("photo cue is generated by tools/make_shutter.py (flash burst)")
